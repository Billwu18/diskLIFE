# diskLIFE launch engine - minimal YAML subset
# Does exactly two things:
#   1) extract the system_prompt block scalar from persona\persona.yml (| and > supported, indentation and newlines kept)
#   2) generate the dsh system-prompt --patch file
# Not a full YAML implementation (no anchors/tags/multi-document/flow collections); see docs\engine.md for the limits.

function ConvertFrom-DPYamlScalar {
    <#
      Handle a single-line scalar: strip quotes, restore common escapes. Unquoted values are returned as-is (trailing comment removed).
    #>
    param([string]$Text)
    if ($null -eq $Text) { return '' }
    $t = $Text.Trim()
    if ($t.Length -eq 0) { return '' }
    if ($t.StartsWith('"') -and $t.EndsWith('"') -and $t.Length -ge 2) {
        $inner = $t.Substring(1, $t.Length - 2)
        $inner = $inner -replace '\\n', "`n" -replace '\\r', "`r" -replace '\\t', "`t" -replace '\\"', '"' -replace '\\\\', '\'
        return $inner
    }
    if ($t.StartsWith("'") -and $t.EndsWith("'") -and $t.Length -ge 2) {
        return ($t.Substring(1, $t.Length - 2) -replace "''", "'")
    }
    # Unquoted: strip a trailing " #comment"
    $idx = $t.IndexOf(' #')
    if ($idx -ge 0) { $t = $t.Substring(0, $idx).TrimEnd() }
    return $t
}

function Join-DPYamlFoldedLines {
    <#
      > folded scalar: a single newline becomes a space, a blank line becomes a real newline.
    #>
    param($Lines)
    $sb = New-Object System.Text.StringBuilder
    foreach ($ln in @($Lines)) {
        if ($ln -eq '') {
            [void]$sb.Append("`n")
            continue
        }
        if ($sb.Length -gt 0 -and -not $sb.ToString().EndsWith("`n")) { [void]$sb.Append(' ') }
        [void]$sb.Append($ln)
    }
    return $sb.ToString()
}

function Read-DPPersonaDocument {
    <#
      Parse persona.yml.
      Returns an object:
        HasSystemPrompt : whether the system_prompt key is present
        SystemPrompt    : the body (LF newlines, no extra trailing blank lines)
        Name            : top-level name: (may be $null)
        Version         : top-level version: / persona_version: (may be $null)
    #>
    param([Parameter(Mandatory = $true)][string]$Path)

    $doc = [pscustomobject]@{
        HasSystemPrompt = $false
        SystemPrompt    = $null
        Name            = $null
        Version         = $null
    }

    $text = Read-DPTextFile -Path $Path
    $text = $text -replace "`r`n", "`n" -replace "`r", "`n"
    $lines = $text.Split("`n")

    foreach ($line in $lines) {
        if (-not $doc.Name -and $line -match '^name\s*:\s*(.+?)\s*$') {
            $doc.Name = ConvertFrom-DPYamlScalar -Text $Matches[1]
            continue
        }
        if (-not $doc.Version -and $line -match '^(?:persona_)?version\s*:\s*(.+?)\s*$') {
            $doc.Version = ConvertFrom-DPYamlScalar -Text $Matches[1]
        }
    }

    for ($i = 0; $i -lt $lines.Length; $i++) {
        $m = [regex]::Match($lines[$i], '^([ \t]*)system_prompt[ \t]*:[ \t]*(.*)$')
        if (-not $m.Success) { continue }

        $keyIndent = $m.Groups[1].Value.Length
        $rest = $m.Groups[2].Value.TrimEnd()
        $doc.HasSystemPrompt = $true

        $style = 'inline'
        if ($rest.StartsWith('|')) { $style = 'literal' }
        elseif ($rest.StartsWith('>')) { $style = 'folded' }
        elseif ($rest.Length -eq 0) { $style = 'plain' }

        if ($style -eq 'inline') {
            $doc.SystemPrompt = ConvertFrom-DPYamlScalar -Text $rest
            return $doc
        }

        $body = New-Object System.Collections.ArrayList
        $contentIndent = -1
        for ($j = $i + 1; $j -lt $lines.Length; $j++) {
            $ln = $lines[$j]
            if ($ln.Trim().Length -eq 0) { [void]$body.Add(''); continue }
            $ind = [regex]::Match($ln, '^[ \t]*').Length
            if ($contentIndent -lt 0) { $contentIndent = $ind }
            if ($ind -le $keyIndent) { break }
            if ($ind -lt $contentIndent) { break }
            [void]$body.Add($ln.Substring($contentIndent))
        }
        while ($body.Count -gt 0 -and $body[$body.Count - 1] -eq '') { $body.RemoveAt($body.Count - 1) }

        if ($style -eq 'folded') {
            $doc.SystemPrompt = Join-DPYamlFoldedLines -Lines $body
        } else {
            $doc.SystemPrompt = (@($body) -join "`n")
        }
        return $doc
    }

    return $doc
}

function New-DPPersonaPatchText {
    <#
      Build the system-prompt patch (replaces the whole config of that id).
      Shape (verified against dsh --dump-config):
        - id: system-prompt
          config:
            personaPrefix: |
              <body>
    #>
    param([Parameter(Mandatory = $true)][AllowEmptyString()][string]$SystemPrompt)

    $normalized = ($SystemPrompt -replace "`r`n", "`n" -replace "`r", "`n")
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append("# diskLIFE: generated by engine\launch.ps1 from persona\persona.yml on the disc; rewritten on every launch.`n")
    [void]$sb.Append("- id: system-prompt`n")
    [void]$sb.Append("  config:`n")
    [void]$sb.Append("    personaPrefix: |`n")
    foreach ($ln in $normalized.Split("`n")) {
        if ($ln.Length -eq 0) {
            [void]$sb.Append("`n")
        } else {
            [void]$sb.Append('      ' + $ln + "`n")
        }
    }
    return $sb.ToString()
}

function New-DPUserPatchTemplate {
    <#
      The user.patch.yml template shown to users (referenced from docs only; users create it themselves).
    #>
    return @'
# Optional: put any extra loader patch you want here (dsh --patch format, top-level array).
# The launcher applies this file first, then persona.patch.yml, so the persona always wins.
- id: system-prompt
  config:
    personaSuffix: |
      (add your own extra notes here)
'@
}
