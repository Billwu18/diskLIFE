'use strict';
// diskLIFE launch engine (Linux) - minimal YAML subset
// Does exactly two things:
//   1) extract the system_prompt block scalar from persona/persona.yml (| and > supported, indentation and newlines kept)
//   2) generate the dsh system-prompt --patch file
// Not a full YAML implementation (no anchors/tags/multi-document/flow collections).
// Ported from engine/lib/Yaml.ps1.

const { readTextFile } = require('./common');

// Handle a single-line scalar: strip quotes, restore common escapes.
// Unquoted values are returned as-is (a trailing " #comment" is removed).
function parseScalar(text) {
  if (text == null) {
    return '';
  }
  let t = String(text).trim();
  if (t.length === 0) {
    return '';
  }
  if (t.length >= 2 && t.startsWith('"') && t.endsWith('"')) {
    const inner = t.slice(1, -1);
    return inner
      .replace(/\\n/g, '\n')
      .replace(/\\r/g, '\r')
      .replace(/\\t/g, '\t')
      .replace(/\\"/g, '"')
      .replace(/\\\\/g, '\\');
  }
  if (t.length >= 2 && t.startsWith("'") && t.endsWith("'")) {
    return t.slice(1, -1).replace(/''/g, "'");
  }
  const idx = t.indexOf(' #');
  if (idx >= 0) {
    t = t.slice(0, idx).replace(/\s+$/, '');
  }
  return t;
}

// > folded scalar: a single newline becomes a space, a blank line becomes a real newline.
function joinFoldedLines(lines) {
  let out = '';
  for (const ln of lines) {
    if (ln === '') {
      out += '\n';
      continue;
    }
    if (out.length > 0 && !out.endsWith('\n')) {
      out += ' ';
    }
    out += ln;
  }
  return out;
}

// Parse persona.yml.
// Returns { hasSystemPrompt, systemPrompt, name, version }.
function readPersonaDocument(filePath) {
  const doc = {
    hasSystemPrompt: false,
    systemPrompt: null,
    name: null,
    version: null,
  };

  const text = readTextFile(filePath).replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const lines = text.split('\n');

  for (const line of lines) {
    if (!doc.name) {
      const m = /^name\s*:\s*(.+?)\s*$/.exec(line);
      if (m) {
        doc.name = parseScalar(m[1]);
        continue;
      }
    }
    if (!doc.version) {
      const m = /^(?:persona_)?version\s*:\s*(.+?)\s*$/.exec(line);
      if (m) {
        doc.version = parseScalar(m[1]);
      }
    }
  }

  for (let i = 0; i < lines.length; i++) {
    const m = /^([ \t]*)system_prompt[ \t]*:[ \t]*(.*)$/.exec(lines[i]);
    if (!m) {
      continue;
    }

    const keyIndent = m[1].length;
    const rest = m[2].replace(/\s+$/, '');
    doc.hasSystemPrompt = true;

    let style = 'inline';
    if (rest.startsWith('|')) {
      style = 'literal';
    } else if (rest.startsWith('>')) {
      style = 'folded';
    } else if (rest.length === 0) {
      style = 'plain';
    }

    if (style === 'inline') {
      doc.systemPrompt = parseScalar(rest);
      return doc;
    }

    const body = [];
    let contentIndent = -1;
    for (let j = i + 1; j < lines.length; j++) {
      const ln = lines[j];
      if (ln.trim().length === 0) {
        body.push('');
        continue;
      }
      const ind = /^[ \t]*/.exec(ln)[0].length;
      if (contentIndent < 0) {
        contentIndent = ind;
      }
      if (ind <= keyIndent) {
        break;
      }
      if (ind < contentIndent) {
        break;
      }
      body.push(ln.slice(contentIndent));
    }
    while (body.length > 0 && body[body.length - 1] === '') {
      body.pop();
    }

    if (style === 'folded') {
      doc.systemPrompt = joinFoldedLines(body);
    } else {
      doc.systemPrompt = body.join('\n');
    }
    return doc;
  }

  return doc;
}

// Build the system-prompt patch (replaces the whole config of that id).
// Exact shape (verified against dsh --dump-config):
//   - id: system-prompt
//     config:
//       personaPrefix: |
//         <body>
function buildPersonaPatchText(systemPrompt) {
  const normalized = (systemPrompt == null ? '' : String(systemPrompt))
    .replace(/\r\n/g, '\n')
    .replace(/\r/g, '\n');
  let out = '# diskLIFE: generated by engine/launch.js from persona/persona.yml on the disc; rewritten on every launch.\n';
  out += '- id: system-prompt\n';
  out += '  config:\n';
  out += '    personaPrefix: |\n';
  for (const ln of normalized.split('\n')) {
    if (ln.length === 0) {
      out += '\n';
    } else {
      out += '      ' + ln + '\n';
    }
  }
  return out;
}

module.exports = {
  buildPersonaPatchText,
  joinFoldedLines,
  parseScalar,
  readPersonaDocument,
};
